export function translate(locale, key, params = {}) {
  const parts = key.split('.')
  let value = translations[locale] ?? translations.en

  for (const part of parts) {
    value = value?.[part]
    if (value === undefined) {
      value = translations.en
      for (const fallbackPart of parts) {
        value = value?.[fallbackPart]
      }
      break
    }
  }

  if (typeof value !== 'string') {
    return key
  }

  return Object.entries(params).reduce(
    (text, [paramKey, paramValue]) => text.replaceAll(`{${paramKey}}`, String(paramValue)),
    value,
  )
}

export function detectDefaultLocale() {
  try {
    const stored = window.localStorage.getItem('talentGraph.language')
    if (stored === 'en' || stored === 'vi') {
      return stored
    }
  } catch {
    // ignore storage errors
  }

  return navigator.language?.toLowerCase().startsWith('vi') ? 'vi' : 'en'
}
